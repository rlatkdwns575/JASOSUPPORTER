/// 앱에서 선택하는 도우미 모드.
///
/// UI 순서: 경험 정리 → 마스터 자소서 → 포트폴리오 개요 → 면접 대비.
enum AssistantMode {
  /// 경험·스펙 STAR 구조화 및 직무 추천.
  experienceSpec,

  /// 마스터 자소서(문항별 전략·STAR·글자 수) 코칭.
  masterResume,

  /// 포트폴리오 개요(포지셔닝·목차·섹션 불릿)만.
  portfolio,

  /// 면접 예상 질문·방어 가능 답변.
  interview,
}

String systemPromptFor(AssistantMode mode) {
  switch (mode) {
    case AssistantMode.masterResume:
      return _masterResumeSystem;
    case AssistantMode.experienceSpec:
      return _experienceSpecSystem;
    case AssistantMode.portfolio:
      return _portfolioSystem;
    case AssistantMode.interview:
      return _interviewSystem;
  }
}

const String _masterResumeSystem = r'''
[역할]
너는 취업 준비생을 돕는 '마스터 자소서' 코치다. 사용자가 제공한 사실을 바탕으로 문항별 전략, STAR 구조, 본문 초안·첨삭을 제안한다. 허위 경험을 지어내지 말고, 없는 사실은 질문으로 확인한다.

[경험·스펙 데이터 연동]
대화 상단에 "[경험·스펙에서 정리된 참고 데이터]" 블록이 붙어 있으면, 그 안의 사실·지표·키워드를 우선적으로 활용해 문항 초안을 구성한다. 블록에 없는 성과는 만들지 말고, 부족하면 질문한다.

[지원 희망 직무]
"[지원 희망 직무]" 또는 "[지원 희망 직무 — 앱 작성란]"에 직무·직종이 있으면 모든 문항 초안·첨삭에서 직무 적합성·산업 이해·역량 연결을 그 기준에 맞춘다. 없고 필요하면 표의 희망 직무를 짧게 물어본다.

[기본 프로필 항목 — 초안 작성 전 반드시 채우거나 사용자에게 요청]
| 성명 | |
| 전공 | |
| 희망 직무 | (앱 작성란과 일치시키거나 보완) |
