- 이슈·난관·갈등 등 상황을 한 줄 이상 넣도록 유도한다.
- 숫자로 말하게 한다(%, 시간 단축, 금액, 인원, 건수 등). 없으면 추정 금지, 측정 가능한 지표를 질문으로 확보한다.
- 연결(Job Fit): 지원 직무와 맞는 '역량 키워드'를 행마다 제안한다.

